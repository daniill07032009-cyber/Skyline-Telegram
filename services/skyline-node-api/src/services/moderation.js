const badWords = [
  'хуй', 'хуя', 'хую', 'хуё', 'хуи', 'хуйн', 'хули', 'хуль',
  'пизд', 'пезд', 'пизж', 'пиздю',
  'бля', 'блят', 'бляд', 'блядь', 'блябу',
  'ебал', 'ебат', 'ебёт', 'ебет', 'ебан', 'ебаш', 'ебуч', 'ебок', 'ебло',
  'ебаный', 'ебанный', 'ебну', 'ёбну', 'ебн',
  'сука', 'суки', 'сук', 'сучк', 'сучён',
  'мудак', 'мудач', 'мудил', 'мудозвон',
  'пидор', 'пидар', 'пидер', 'пидр',
  'гандон', 'гондон',
  'залуп', 'залуп',
  'дроч', 'дрочит', 'дрочер',
  'манда', 'манд',
  'шлюх', 'шлюш',
  'гнида', 'гнид'
];

function containsProfanity(text) {
  if (!text) return false;
  const lowerText = text.toLowerCase();
  // Разбиваем на слова, убираем знаки препинания
  const words = lowerText.split(/[^а-яёa-z0-9]+/);
  
  for (const word of words) {
    for (const bad of badWords) {
      if (word.includes(bad)) {
        return true;
      }
    }
  }
  return false;
}

module.exports = { containsProfanity };